    public static object Create(NavItem item, SubTab tab)
    {
        return item.Key switch
        {
            "settings" => new SettingsView { Section = tab.Key },
            _ => CreatePlaceholder(tab.Key),
        };
    }

    private static PlaceholderView CreatePlaceholder(string tabKey)
    {
        var text = Describe(tabKey);
        return new PlaceholderView
        {
            Heading = text.Title,
            Stage = text.Stage,
            Note = text.Note,
            Bullets = text.Bullets,
        };
    }

